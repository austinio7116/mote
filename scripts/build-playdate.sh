#!/usr/bin/env bash
# Build Mote for the Playdate: one Mote.pdx with the launcher and every game.
#
#   ./scripts/build-playdate.sh            -> dist-playdate/Mote.pdx (+ .zip)
#   ./scripts/build-playdate.sh --sim      simulator build only (no device pdex)
#
# Needs the Playdate SDK (PLAYDATE_SDK_PATH, default ~/PlaydateSDK-*) and
# arm-none-eabi-gcc. Sideload the .pdx at play.date/account/sideload or copy it
# to the Games folder in the Playdate's data disk mode.
#
# A Playdate pdex is one statically linked program -- nothing is loaded at run
# time -- so the games are linked in rather than dlopen'd. Each game is built on
# its own, partially linked (ld -r), and then objcopy renames its six entry
# symbols to mg_<stem>_* and makes every other symbol it defines local. Two games
# can then both have a `player` or a `draw_hud` without colliding, exactly as if
# each were still its own module. mote_pd_games.c is generated to list them.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
SDK="${PLAYDATE_SDK_PATH:-$(ls -d "$HOME"/PlaydateSDK-* 2>/dev/null | sort -V | tail -1)}"
[ -d "$SDK/C_API" ] || { echo "no Playdate SDK (set PLAYDATE_SDK_PATH)" >&2; exit 1; }
B=build_playdate
OUT=dist-playdate
SIM_ONLY=0
[ "${1:-}" = --sim ] && SIM_ONLY=1

ENGINE=(engine/render/mote_raster.c engine/render/mote_pipe.c engine/render/mote_scene3d.c
        engine/render/mote_splat.c engine/render/mote_font.c engine/render/mote_2d.c
        engine/physics/mote_phys.c engine/physics/mote_phys2d.c engine/audio/mote_audio.c
        engine/core/mote_perf.c engine/core/mote_arena.c engine/input/mote_input.c)
OS=(os/mote_os.c os/mote_launcher.c os/mote_ui.c os/mote_menu.c os/mote_lobby.c os/mote_netshim.c)
PLAT=(platform/playdate/mote_plat_playdate.c platform/playdate/mote_pd_main.c)
INCS=(-Iengine/core -Iengine/math -Iengine/render -Iengine/assets -Iengine/input
      -Iengine/physics -Iengine/audio -Iengine/scene -Isdk -Ios -Iplatform/playdate
      -I"$SDK/C_API")
# Game code is gcc-clean on the Thumby but carries K&R ports and implicit
# cross-module calls; match the other module builds' leniency.
LENIENT=(-Wno-implicit-function-declaration -Wno-unused -Wno-format-truncation)
EXPORTS=(mote_game_register mote_game_abi_version mote_game_name mote_game_author
         mote_game_icon_data mote_game_version)

GAMES=()
for d in games/*/; do
    compgen -G "$d/src/*.c" >/dev/null || continue
    GAMES+=("$(basename "$d")")
done

# build_target <dev|sim>
build_target() {
    local t=$1 CC OBJCOPY LD CFLAGS
    if [ "$t" = dev ]; then
        CC=arm-none-eabi-gcc; OBJCOPY=arm-none-eabi-objcopy; LD=arm-none-eabi-ld
        CFLAGS=(-mthumb -mcpu=cortex-m7 -mfloat-abi=hard -mfpu=fpv5-sp-d16 -D__FPU_USED=1
                -DTARGET_PLAYDATE=1 -DTARGET_EXTENSION=1 -DMOTE_DEVICE=1 -DMOTE_PLAYDATE=1 -DNDEBUG -g
                -O2 -ffast-math -falign-functions=16 -fomit-frame-pointer
                -mword-relocations -fno-common -ffunction-sections -fdata-sections -std=gnu11)
    else
        CC=gcc; OBJCOPY=objcopy; LD=ld
        # Compiled as the device is (MOTE_DEVICE: games skip stdio/getenv, and
        # the OS sizes its arena and sound pools the same), so the Simulator
        # shows what a Playdate will. Moria's fiber takes its thread backend
        # here; its Cortex-M switch is device-only.
        CFLAGS=(-fPIC -g -O2 -ffast-math -DTARGET_SIMULATOR=1 -DTARGET_EXTENSION=1
                -DMOTE_DEVICE=1 -DMOTE_PLAYDATE=1 -DMOTE_FIBER_PTHREAD=1 -DNDEBUG -fno-common -std=gnu11)
    fi
    local o="$B/$t"
    rm -rf "$o"; mkdir -p "$o/core" "$o/games"

    echo "==> [$t] engine + OS + platform"
    local objs=()
    for f in "${ENGINE[@]}" "${OS[@]}" "${PLAT[@]}"; do
        local ob="$o/core/$(echo "$f" | tr / _).o"
        "$CC" -c "${CFLAGS[@]}" "${INCS[@]}" "$f" -o "$ob"
        objs+=("$ob")
    done

    echo "==> [$t] games"
    local gtab="$o/mote_pd_games.c"
    {
        echo '/* generated by scripts/build-playdate.sh */'
        echo '#include "mote_pd_games.h"'
    } > "$gtab"
    local ok=()
    for g in "${GAMES[@]}"; do
        local gd="games/$g" go="$o/games/$g"
        mkdir -p "$go"
        local cf=()
        [ -f "$gd/cflags" ] && while read -r tok; do cf+=("$tok"); done < <(sed 's/#.*//' "$gd/cflags" | tr -s ' \n' '\n' | sed '/^$/d')
        local gobjs=() fail=0
        for f in "$gd"/src/*.c; do
            case "${f##*/}" in test_*.c) continue;; esac
            local ob="$go/$(basename "$f" .c).o"
            if ! "$CC" -c "${CFLAGS[@]}" "${LENIENT[@]}" "${cf[@]}" "${INCS[@]}" -I"$gd/src" "$f" -o "$ob" 2>>"$go/build.log"; then
                fail=1; break
            fi
            gobjs+=("$ob")
        done
        if [ $fail = 1 ]; then echo "  FAIL $g (see $go/build.log)"; grep -m3 error "$go/build.log" | sed 's/^/        /'; continue; fi
        "$LD" -r -o "$go/game.r.o" "${gobjs[@]}"
        local ren=() keep=()
        for s in "${EXPORTS[@]}"; do
            ren+=(--redefine-sym "$s=mg_${g}_$s"); keep+=(--keep-global-symbol "mg_${g}_$s")
        done
        "$OBJCOPY" "${ren[@]}" "${keep[@]}" "$go/game.r.o" "$go/game.o"
        objs+=("$go/game.o")
        ok+=("$g")
        printf '  ok   %s\n' "$g"
    done
    for g in "${ok[@]}"; do
        cat >> "$gtab" <<C
extern const MoteGameVtbl *mg_${g}_mote_game_register(const MoteApi *);
extern const char *const mg_${g}_mote_game_name __attribute__((weak));
extern const unsigned char mg_${g}_mote_game_icon_data[] __attribute__((weak));
C
    done
    echo 'const MotePdGame mote_pd_games[] = {' >> "$gtab"
    for g in "${ok[@]}"; do
        echo "    { \"$g\", mg_${g}_mote_game_register, &mg_${g}_mote_game_name, mg_${g}_mote_game_icon_data }," >> "$gtab"
    done
    echo '};' >> "$gtab"
    echo "const int mote_pd_ngames = ${#ok[@]};" >> "$gtab"
    "$CC" -c "${CFLAGS[@]}" "${INCS[@]}" "$gtab" -o "$o/mote_pd_games.o"
    objs+=("$o/mote_pd_games.o")

    echo "==> [$t] link"
    if [ "$t" = dev ]; then
        "$CC" -c "${CFLAGS[@]}" "${INCS[@]}" "$SDK/C_API/buildsupport/setup.c" -o "$o/setup.o"
        "$CC" -c "${CFLAGS[@]}" "${INCS[@]}" platform/playdate/mote_pd_syscalls.c -o "$o/syscalls.o"
        # The SDK's link map, plus the section MOTE_HOT functions go to.
        sed 's/\*(\.text\.\*)/*(.text.*)\n\t\t*(.time_critical*)/' \
            "$SDK/C_API/buildsupport/link_map.ld" > "$o/link_map.ld"
        "$CC" "$o/setup.o" "$o/syscalls.o" "${objs[@]}" -nostartfiles \
              -mthumb -mcpu=cortex-m7 -mfloat-abi=hard -mfpu=fpv5-sp-d16 \
              -T"$o/link_map.ld" -Wl,-Map="$o/pdex.map",--gc-sections,--no-warn-mismatch,--emit-relocs \
              -o "$o/pdex.elf"
        arm-none-eabi-size "$o/pdex.elf"
    else
        "$CC" -shared -fPIC "${INCS[@]}" "$SDK/C_API/buildsupport/setup.c" \
              -DTARGET_SIMULATOR=1 -DTARGET_EXTENSION=1 "${objs[@]}" -lm -lpthread -o "$o/pdex.so"
    fi
}

build_target sim
[ $SIM_ONLY = 1 ] || build_target dev

echo "==> pdc"
SRC="$B/Source"
rm -rf "$SRC"; mkdir -p "$SRC/launcher"
strip --strip-debug -o "$SRC/pdex.so" "$B/sim/pdex.so"
[ $SIM_ONLY = 1 ] || cp "$B/dev/pdex.elf" "$SRC/"
cp platform/playdate/pdxinfo "$SRC/"
cp platform/playdate/launcher/*.png "$SRC/launcher/"
mkdir -p "$OUT"; rm -rf "$OUT/Mote.pdx"
# pdc is built against glibc 2.38; run it natively where that works, else in
# a stock Ubuntu 24.04 container (scripts/playdate/Dockerfile).
if "$SDK/bin/pdc" --version >/dev/null 2>&1; then
    "$SDK/bin/pdc" -sdkpath "$SDK" "$SRC" "$OUT/Mote.pdx"
else
    docker build -q -t mote-playdate scripts/playdate >/dev/null
    docker run --rm --user "$(id -u):$(id -g)" -v "$SDK":/sdk:ro -v "$ROOT":/src -w /src \
        mote-playdate /sdk/bin/pdc -sdkpath /sdk "$SRC" "$OUT/Mote.pdx"
fi
( cd "$OUT" && rm -f Mote-playdate.zip && zip -qr Mote-playdate.zip Mote.pdx )
echo "==> $OUT/Mote.pdx ($(du -sh "$OUT/Mote.pdx" | cut -f1))"
